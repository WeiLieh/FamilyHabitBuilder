// =============================================================================
// tests/nudge-repository-first-load.test.ts: the owner's first-load CSVs pass the app's rules
//
// src/datastore/supabase/seed/nudges-first-load.csv and examples-first-load.csv were made
// from docs/archive/Nudge_Repository.xlsx. The owner imports them into Supabase once
// (nudges first, then examples). The database has its own rules (tested by
// src/datastore/src/datastore/supabase/tests/); this test checks the APP's rules accept the same data, so
// the two sets of rules agree.
// =============================================================================

import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { readNudgeRows } from "../src/nudge-repository/nudge-repository.js";
import { csvToObjects } from "./helpers/csv.js";

// Read a CSV and shape each row the way Supabase will return it: IDs 1, 2, 3...
// (generated by the database in file order), true/false as yes/no values,
// numbers as numbers, and empty cells as "nothing" (null). Examples have no
// "active" column in the CSV; the database fills in yes (true).
function rowsAsSupabaseReturnsThem(file: string, defaults: Record<string, unknown> = {}) {
  const text = readFileSync(file, "utf8");
  return csvToObjects(text).map((row, index) => {
    const shaped: Record<string, unknown> = { id: index + 1, ...defaults };
    for (const [column, value] of Object.entries(row)) {
      if (value === "true" || value === "false") shaped[column] = value === "true";
      else if (column === "description_max_chars") shaped[column] = Number(value);
      else shaped[column] = value === "" ? null : value;
    }
    return shaped;
  });
}

describe("First-load CSVs for the Supabase nudges and examples tables", () => {
  const result = readNudgeRows(
    rowsAsSupabaseReturnsThem("src/datastore/supabase/seed/nudges-first-load.csv"),
    rowsAsSupabaseReturnsThem("src/datastore/supabase/seed/examples-first-load.csv", { active: true }),
  );

  it("has 9 nudges, every one passes the app's checks, and none is short of examples", () => {
    expect(result.problems).toEqual([]);
    expect(result.shortages).toEqual([]);
    expect(result.nudges).toHaveLength(9);
  });

  it("uses the agreed codes, with 4 quick and 5 deliberate nudges (spec v1.3, v1.6)", () => {
    const summary = result.nudges.map((n) => `${n.code} ${n.category} ${n.name}`);
    expect(summary).toEqual([
      "TWC quick Talking with children",
      "SAF quick Showing affection",
      "DPR quick Descriptive praise",
      "GAT quick Giving attention",
      "SQT deliberate Spending quality time",
      "IAC deliberate Interesting activities",
      "SGE deliberate Setting a good example",
      "ITE deliberate Incidental teaching",
      "ASD deliberate Ask-say-do",
    ]);
  });

  it("has the owner's 5 examples for every nudge (45 in total)", () => {
    expect(result.nudges.every((n) => n.examples.length === 5)).toBe(true);
  });

  it("has examples with no time of day baked in, so Claude can fit them to any nudge slot (spec v1.7)", () => {
    // Words that tie an example to one part of the day. Claude adds timing
    // context itself, based on when the nudge message is sent.
    const timeWords = /\b(morning|breakfast|lunch|lunchbox|dinner|supper|evening|tonight|night|bedtime|after homework|on the way home|leaves for school)\b/i;
    const timeBound = result.nudges
      .flatMap((n) => n.examples)
      .filter((e) => timeWords.test(e.text))
      .map((e) => e.text);
    expect(timeBound).toEqual([]);
  });

  it("starts with all 9 nudges unlocked (rule 2.2, changed 29 Oct: unlocks are out of the MVP)", () => {
    expect(result.nudges.filter((n) => !n.startsUnlocked).map((n) => n.code)).toEqual([]);
  });

  it("allows photos (with a photo idea) for exactly the 5 deliberate nudges, self-report for all 9", () => {
    expect(result.nudges.filter((n) => n.photoUploadAllowed).every((n) => n.photoIdea !== null)).toBe(true);
    expect(result.nudges.filter((n) => n.photoUploadAllowed)).toHaveLength(5);
    expect(result.nudges.every((n) => n.selfReportAllowed && n.active)).toBe(true);
  });
});
