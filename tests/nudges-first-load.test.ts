// =============================================================================
// tests/nudges-first-load.test.ts: the owner's first-load CSV passes the app's rules
//
// supabase/seed/nudges-first-load.csv was made from docs/Nudge_Repository.xlsx
// and is what the owner imports into Supabase once. The database has its own
// rules (tested by supabase/tests/), and this test checks the APP's rules
// accept the same 9 nudges, so the two sets of rules agree.
// =============================================================================

import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { readNudgeRows } from "../shared/nudge-repository.js";
import { csvToObjects } from "./helpers/csv.js";

// Read the CSV and shape each row the way Supabase will return it: IDs 1 to 9
// (generated by the database in file order), true/false as yes/no values,
// numbers as numbers, and empty cells as "nothing" (null).
function rowsAsSupabaseReturnsThem(): Record<string, unknown>[] {
  const text = readFileSync("supabase/seed/nudges-first-load.csv", "utf8");
  return csvToObjects(text).map((row, index) => {
    const shaped: Record<string, unknown> = { id: index + 1 };
    for (const [column, value] of Object.entries(row)) {
      if (value === "true" || value === "false") shaped[column] = value === "true";
      else if (column === "description_max_chars") shaped[column] = Number(value);
      else shaped[column] = value === "" ? null : value;
    }
    return shaped;
  });
}

describe("First-load CSV for the Supabase nudges table", () => {
  const result = readNudgeRows(rowsAsSupabaseReturnsThem());

  it("has 9 nudges and every one passes the app's checks", () => {
    expect(result.problems).toEqual([]);
    expect(result.nudges).toHaveLength(9);
  });

  it("has 4 quick and 5 deliberate nudges, as in the owner's spreadsheet (spec v1.3)", () => {
    expect(result.nudges.filter((n) => n.category === "quick").map((n) => n.name)).toEqual([
      "Talking with children",
      "Showing affection",
      "Descriptive praise",
      "Giving attention",
    ]);
    expect(result.nudges.filter((n) => n.category === "deliberate").map((n) => n.name)).toEqual([
      "Spending quality time",
      "Interesting activities",
      "Setting a good example",
      "Incidental teaching",
      "Ask-say-do",
    ]);
  });

  it("starts unlocked: all 4 quick plus spending quality time and interesting activities (spec v1.5)", () => {
    expect(result.nudges.filter((n) => !n.startsUnlocked).map((n) => n.name)).toEqual([
      "Setting a good example",
      "Incidental teaching",
      "Ask-say-do",
    ]);
  });

  it("allows photos (with a photo idea) for exactly the 5 deliberate nudges, self-report for all 9", () => {
    expect(result.nudges.filter((n) => n.photoUploadAllowed).every((n) => n.photoIdea !== null)).toBe(true);
    expect(result.nudges.filter((n) => n.photoUploadAllowed)).toHaveLength(5);
    expect(result.nudges.every((n) => n.selfReportAllowed && n.active)).toBe(true);
  });
});
