-- =============================================================================
-- supabase/migrations/001_create_nudge_repository.sql: the Nudge repository
--
-- What it does: creates the two tables the owner edits in the Supabase
-- dashboard (spec v1.6):
--   nudges   - one row per nudge: a short code (e.g. TWC), its name, category
--              and settings, each written once
--   examples - one row per example, naming its nudge by that code; as many
--              examples per nudge as you like
-- plus a read-only combined view for browsing, and a guard that refuses edits
-- which would leave a nudge with fewer than 3 active examples.
-- The database refuses badly formed rows, using the same rules as the app's
-- checks in shared/nudge-repository.ts ("defence in depth").
--
-- How to apply: the owner opens Supabase > SQL Editor, pastes this whole file
-- and clicks Run. Run it once only (running again fails because the tables
-- already exist, which is safe: nothing is changed).
--
-- SQL (Structured Query Language) is the language databases understand.
-- "--" starts a comment, which the database ignores.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- Table 1: nudges
-- ---------------------------------------------------------------------------
create table public.nudges (
  -- ID: a whole number the database generates (1, 2, 3...). "generated always"
  -- means nobody can type their own ID, so IDs can never be duplicated.
  -- Parents' choices, history and metrics point to this number.
  id bigint generated always as identity primary key,

  -- Short code the owner types when adding examples, e.g. TWC. 2 to 10
  -- capital letters or digits ("~" means "matches this pattern"). Unique.
  code text not null unique check (code ~ '^[A-Z0-9]{2,10}$'),

  -- The nudge's name, e.g. "Descriptive praise". Must not be blank.
  name text not null check (btrim(name) <> ''),

  -- "quick" (1 to 2 minutes) or "deliberate" (more time). Nothing else.
  category text not null check (category in ('quick', 'deliberate')),

  -- Yes/no columns ("boolean" = true or false; empty is not allowed).
  self_report_allowed boolean not null,

  -- Longest optional description a parent may add when logging (1 to 280).
  description_max_chars integer not null default 280
    check (description_max_chars between 1 and 280),

  photo_upload_allowed boolean not null,

  -- What to photograph. Required only when photos are allowed (rule below).
  photo_idea text,

  -- No = retired: parents can't pick it, but its history stays.
  -- Retire a nudge instead of deleting it.
  active boolean not null default true,

  -- No = a parent must unlock it before picking it.
  starts_unlocked boolean not null,

  -- When the row was added (filled in automatically).
  created_at timestamptz not null default now(),

  -- Rules that compare two columns:
  -- a nudge that allows photos needs a photo idea...
  constraint photo_idea_required_when_photos_allowed
    check (not photo_upload_allowed or (photo_idea is not null and btrim(photo_idea) <> '')),
  -- ...and every nudge needs at least one way to log.
  constraint at_least_one_way_to_log
    check (self_report_allowed or photo_upload_allowed)
);

-- No two nudges may share a name. Capitals and extra spaces are ignored, so
-- "Showing affection" and "  showing  AFFECTION" count as the same name.
create unique index nudges_name_unique
  on public.nudges (lower(regexp_replace(btrim(name), '\s+', ' ', 'g')));

comment on table public.nudges is
  'Nudge repository: one row per nudge. Retire with active = false instead of deleting. Examples live in the examples table.';

-- ---------------------------------------------------------------------------
-- Table 2: examples
-- ---------------------------------------------------------------------------
create table public.examples (
  -- ID: generated by the database and never changes, so metrics can tell
  -- which example worked.
  id bigint generated always as identity primary key,

  -- Which nudge this example belongs to, by its code. "references" makes the
  -- database check the code exists in the nudges table, so a typo such as
  -- "TCW" is refused. "on update cascade": if a nudge's code is ever changed,
  -- its examples follow automatically. "on delete restrict": a nudge that
  -- still has examples cannot be deleted (retire it instead).
  nudge_code text not null
    references public.nudges (code) on update cascade on delete restrict,

  -- The example text. Must not be blank.
  example text not null check (btrim(example) <> ''),

  -- No = retired example (kept for history, not used in nudge messages).
  active boolean not null default true,

  created_at timestamptz not null default now()
);

-- Makes "all examples for nudge TWC" fast to look up.
create index examples_nudge_code on public.examples (nudge_code);

comment on table public.examples is
  'Nudge repository: one row per example, linked to its nudge by code. Keep at least 3 active examples per nudge. Retire with active = false.';

-- ---------------------------------------------------------------------------
-- Guard: keep at least 3 active examples per nudge (spec v1.6, "block")
-- ---------------------------------------------------------------------------
-- A "trigger" is a small program the database runs automatically after a
-- change. This one runs after an example is deleted or edited. If that change
-- took an active example away from a nudge (deleted, retired, or moved to
-- another code) and the nudge is left with fewer than 3, the database refuses
-- the whole change and shows the message below in the dashboard.
-- Adding a brand-new nudge is not blocked (its examples are added one by one);
-- the app flags those instead ("alert").
-- The number 3 must match MIN_EXAMPLES_PER_NUDGE in shared/settings.ts.
create function public.examples_keep_minimum() returns trigger
language plpgsql
set search_path = '' -- security: only use the names written in full below
as $$
declare
  min_examples constant integer := 3;
  remaining integer;
begin
  -- Only changes that take away an ACTIVE example matter.
  if not old.active then
    return null;
  end if;
  if tg_op = 'UPDATE' and new.active and new.nudge_code = old.nudge_code then
    return null; -- e.g. only the text was edited
  end if;

  -- If the nudge's code itself was changed, its examples simply followed it;
  -- nothing was taken away.
  if not exists (select 1 from public.nudges where code = old.nudge_code) then
    return null;
  end if;

  select count(*) into remaining
  from public.examples
  where nudge_code = old.nudge_code and active;

  if remaining < min_examples then
    raise exception
      'Can''t do this: nudge % would have only % active example(s) (minimum %). Add another example first.',
      old.nudge_code, remaining, min_examples
      using errcode = 'check_violation';
  end if;
  return null;
end;
$$;

create trigger examples_keep_minimum
  after update or delete on public.examples
  for each row execute function public.examples_keep_minimum();

-- ---------------------------------------------------------------------------
-- Read-only combined view, for browsing in the dashboard
-- ---------------------------------------------------------------------------
-- A "view" is a saved question that looks like a table: here, every example
-- next to its nudge's code, name and category. You browse it; you edit the
-- two tables. "security_invoker" means it obeys the same access rules as the
-- tables underneath.
create view public.nudge_examples_view with (security_invoker = true) as
select
  n.code,
  n.name,
  n.category,
  e.id as example_id,
  e.example,
  e.active as example_active,
  n.active as nudge_active
from public.examples e
join public.nudges n on n.code = e.nudge_code
order by n.id, e.id;

-- ---------------------------------------------------------------------------
-- Security
-- ---------------------------------------------------------------------------
-- Supabase can publish tables on the internet through its automatic web
-- interface (the "Data API"). Row Level Security (RLS) on, with no rules,
-- means nobody gets in that way by default.
alter table public.nudges enable row level security;
alter table public.examples enable row level security;

-- Only our own server code (which signs in with the secret "service role" key,
-- kept in Vercel) may READ the two tables. Nobody may add, change or delete
-- rows through the Data API; the owner edits them in the dashboard instead.
-- (Supabase requires these permissions to be granted explicitly.)
revoke all on public.nudges, public.examples, public.nudge_examples_view from anon, authenticated;
grant select on public.nudges, public.examples to service_role;

-- The guard runs automatically; nobody needs to call it directly.
revoke execute on function public.examples_keep_minimum() from public, anon, authenticated;
